-- Ledger events are append-only at the API/service layer. Reversals must
-- reference the original payment, never overwrite or delete its history.
-- Phase 1D adds PostgreSQL row locks for concurrent payment safety.

CREATE TABLE public.treatment_payments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  treatment_id TEXT NOT NULL REFERENCES public.treatments(treatment_id),
  amount_cents BIGINT NOT NULL CHECK (amount_cents <> 0),
  payment_date DATE,
  payment_method TEXT NOT NULL DEFAULT 'Not recorded',
  reference TEXT NOT NULL DEFAULT '',
  notes TEXT NOT NULL DEFAULT '',
  source TEXT NOT NULL CHECK (source IN ('opening', 'initial', 'recorded', 'reversal')),
  reverses_payment_id INTEGER UNIQUE REFERENCES public.treatment_payments(id),
  request_id TEXT UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT payment_reversal_shape CHECK (
    (source = 'reversal' AND amount_cents < 0 AND reverses_payment_id IS NOT NULL)
    OR
    (source <> 'reversal' AND amount_cents > 0 AND reverses_payment_id IS NULL)
  )
);

CREATE INDEX idx_treatment_payments_treatment
  ON public.treatment_payments(treatment_id, id);
