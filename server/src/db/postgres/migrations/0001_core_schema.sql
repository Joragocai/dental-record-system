-- PostgreSQL 1B: clean single-clinic schema, no live SQLite data is imported.
-- Dates use DATE, timestamps use TIMESTAMPTZ, and clinical yes/no flags
-- remain 0/1 SMALLINT to preserve the existing API's data model.
-- Phase 1C must serialize dates as YYYY-MM-DD and timestamps as ISO strings.
-- Empty optional date/time form values must be normalized to NULL on write.

