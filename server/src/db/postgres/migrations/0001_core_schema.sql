CREATE TABLE public.treatments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  treatment_id TEXT NOT NULL UNIQUE CHECK (treatment_id ~ '^T-[0-9]{4}-[0-9]{4}$'),
  patient_id TEXT NOT NULL REFERENCES public.patients(patient_id),
  treatment_date DATE NOT NULL,
  tooth_numbers TEXT,
  next_appointment TEXT,
  next_appointment_date DATE,
  next_appointment_time TEXT,
  procedure TEXT NOT NULL,
  dentists TEXT NOT NULL,
  amount_charged NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (amount_charged >= 0),
  discount_type TEXT DEFAULT 'None',
  discount_percent NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (discount_percent >= 0 AND discount_percent <= 100),
  discount_amount NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
  net_amount_due NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (net_amount_due >= 0),
  amount_paid NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (amount_paid >= 0),
  balance NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (balance >= 0),
  remarks TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE public.appointments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id TEXT NOT NULL REFERENCES public.patients(patient_id),
  appointment_date DATE NOT NULL,
  appointment_time TEXT,
  planned_procedure TEXT,
  notes TEXT,
  status TEXT NOT NULL DEFAULT 'Scheduled' CHECK (status IN ('Scheduled', 'Completed', 'Cancelled', 'No-show')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE public.attachments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id TEXT NOT NULL REFERENCES public.patients(patient_id),
  treatment_id TEXT REFERENCES public.treatments(treatment_id),
  attachment_type TEXT NOT NULL,
  original_filename TEXT NOT NULL,
  stored_filename TEXT NOT NULL,
  file_path TEXT NOT NULL,
  mime_type TEXT,
  file_size BIGINT CHECK (file_size >= 0),
  uploaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
