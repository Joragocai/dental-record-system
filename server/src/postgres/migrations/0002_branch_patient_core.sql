CREATE TABLE IF NOT EXISTS branches (
  id UUID PRIMARY KEY,
  branch_code TEXT NOT NULL UNIQUE,
  branch_name TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL,
  CONSTRAINT branches_branch_code_not_blank CHECK (length(trim(branch_code)) > 0),
  CONSTRAINT branches_branch_name_not_blank CHECK (length(trim(branch_name)) > 0)
);

CREATE TABLE IF NOT EXISTS patient_code_counters (
  calendar_year INTEGER PRIMARY KEY,
  last_sequence INTEGER NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL,
  CONSTRAINT patient_code_counters_year_positive CHECK (calendar_year >= 2000),
  CONSTRAINT patient_code_counters_sequence_positive CHECK (last_sequence >= 1)
);

