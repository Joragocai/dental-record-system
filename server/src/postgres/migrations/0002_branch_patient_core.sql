CREATE TABLE IF NOT EXISTS legacy_patient_identity_map (
  source_system TEXT NOT NULL,
  legacy_patient_row_id BIGINT NOT NULL,
  legacy_patient_code TEXT NOT NULL,
  patient_id UUID NOT NULL REFERENCES patients(id) ON DELETE RESTRICT,
  created_at TIMESTAMPTZ NOT NULL,
  CONSTRAINT legacy_patient_identity_map_source_not_blank CHECK (length(trim(source_system)) > 0),
  CONSTRAINT legacy_patient_identity_map_code_not_blank CHECK (length(trim(legacy_patient_code)) > 0),
  CONSTRAINT legacy_patient_identity_map_source_row_unique UNIQUE (source_system, legacy_patient_row_id),
  CONSTRAINT legacy_patient_identity_map_source_code_unique UNIQUE (source_system, legacy_patient_code),
  CONSTRAINT legacy_patient_identity_map_patient_unique UNIQUE (patient_id)
);
